import string
import unicodedata

import numpy as np
import sentence_transformers

from kaggle_benchmarks import actors, benchmark, llm, llms, task, utils

# %% [markdown]
# ## Exact Match Assertion
# The simplest evaluation asserts an exact match between the LLM's output and an expected string.
# While precise, this is highly sensitive to minor variations and is typically too strict for varied LLM responses, especially for longer phrases.

# Let's start with a basic factual query about the Oulipo acronym.
# %%


@task(name="Oulipo Acronym Definition")
def check_oulipo_acronym_definition(llm):
    """Checks if the LLM provides the exact definition of the Oulipo acronym."""
    prompt = "What does Oulipo stand for?"
    expected_definition = "Ouvroir de littérature potentielle"

    answer = llm.prompt(prompt)
    assert answer == expected_definition, f"Expected '{expected_definition}'"


check_oulipo_acronym_definition.evaluate(llm=llms.values())

# %% [markdown]
# As demonstrated, exact match assertions frequently fail due to minor output variations (extra text, casing, punctuation, diacritics) even when the core information is correct.
# This is particularly true for longer or foreign phrases like "Ouvroir de littérature potentielle".

# To handle variations robustly, **text normalization** should be applied.
# Normalization converts text to a consistent form by:
# 1.  Lowercasing.
# 2.  Removing punctuation.
# 3.  Removing diacritics.
# 4.  Collapsing whitespace.

# Applying normalization to both the LLM output and the expected text gives more reliable comparisons, regardless of minor formatting differences.
# %%


def normalize_text(text: str) -> str:
    """Converts text to lowercase, removes punctuation and diacritics,
    and collapses multiple whitespaces to a single space.
    """
    text = unicodedata.normalize("NFKD", text).encode("ASCII", "ignore").decode("utf-8")
    text = text.lower()
    text = text.translate(str.maketrans("", "", string.punctuation))
    text = " ".join(text.strip().split())
    return text


@task(name="Oulipo Acronym Definition")
def check_oulipo_acronym_normalized(llm):
    """Checks if the normalized definition of the Oulipo acronym is present in the normalized response."""
    expected_normalized_keyword = normalize_text("Ouvroir de littérature potentielle")

    prompt = "What does Oulipo stand for?"
    answer = llm.prompt(prompt)
    normalized_response = normalize_text(answer)

    assert expected_normalized_keyword in normalized_response, (
        f"'{expected_normalized_keyword}' not found in normalized response."
    )


check_oulipo_acronym_normalized.evaluate(llm=llms.values())

#  %% [markdown]
# ## Evaluating Generated Text: Constraint Checks
# Evaluation can also involve checking properties of text generated by an LLM, based on specified constraints.

# A **Lipogram** is a text intentionally written to avoid a specific letter.
# This serves as an example of a generative task involving a specific character-level constraint.
# We can define a task to prompt for a lipogram and assert the absence of the forbidden letter.


# %%
@task(name="Lipogram")
def generate_lipogram_poem(llm, letter: str = "e"):
    """Asks LLM to write a poem without a specific letter and asserts the constraint."""
    prompt = f"Write a short, four-line poem about creativity without using the letter '{letter}'."
    actors.system.send("Write a poem only.")
    poem = llm.prompt(prompt)
    forbidden_letter = letter.lower()
    higlihgted = utils.highlight_matched_spans(poem, forbidden_letter, "red")
    assert forbidden_letter not in poem.lower(), (
        f"Found forbidden letter '{forbidden_letter}' in poem:\n{higlihgted}"
    )


# %%
# Evaluating Lipogram generation for multiple letters via parameterization:
generate_lipogram_poem.evaluate(llm=[llm], letter="aefk").group_by("llm")
# %% [markdown]
# Other examples of generative constraints suitable for assertion-based checks include:

# * **Univocalism**: A text using only one specific vowel letter (or no vowels).
# * **Tautogram**: A text where every word begins with the same letter.
# %%


@task("Univocalism")
def generate_univocal_story(llm, vowel: str, min_words: int = 10):
    """Asks the LLM to write a story using only one specified vowel."""
    actors.system.send("Write a story only.")
    story = llm.prompt(
        f"Write a story with at least {min_words} words using only one vowel '{vowel}'."
    )
    vowels = "aeiou"

    n_words = len(story.split())
    assert n_words >= min_words, (
        f"Story has only {n_words}, must be at least {min_words}."
    )
    assert set(vowels) & set(story) == {vowel}, (
        f"Story contains other vowels: {set(vowels) & set(story) - {vowel}}."
    )


generate_univocal_story.run(llm=llm, vowel="e")

# %%


@task("Tautogram")
def generate_tautogram_story(llm, letter: str, min_words: int = 10):
    """Asks the LLM to write a story where every word starts with a specific letter."""
    actors.system.send("Write a story only.")
    story = llm.prompt(
        f"Write a tautogram story with at least {min_words} using only words that start with '{letter}'."
    )

    n_words = len(story.split())
    assert n_words >= min_words, (
        f"Story has only {n_words}, must be at least {min_words}."
    )
    mistakes = (w for w in normalize_text(story) if not w.startswith(letter))
    assert not mistakes, f"Words not starting with {letter}: {','.join(mistakes)}"


generate_tautogram_story.run(llm=llm, letter="e")

# %% [markdown] Collecting Tasks in a Single Benchmark
#
# Individual tasks test specific capabilities. Grouping related tasks into a **benchmark** suite provides a consolidated evaluation view. The `@benchmark` decorator defines these suites.

# This example creates a task executing multiple subtasks with varying parameters within a single suite.
# %%


@benchmark()
def oulipo_generative_benchmark(llm):
    generate_lipogram_poem.run(llm, letter="k")
    generate_lipogram_poem.run(llm, letter="e")
    generate_lipogram_poem.run(llm, letter="t")
    generate_univocal_story.run(llm, vowel="a")
    generate_univocal_story.run(llm, vowel="e")
    generate_tautogram_story.run(llm, letter="i")
    generate_tautogram_story.run(llm, letter="s")
    generate_tautogram_story.run(llm, letter="b")


oulipo_generative_benchmark.evaluate(llm=llms.values()).group_by("llm")


# %% [markdown] Unsupervised Evaluation: Semantic Diversity
#
# For generative tasks without a single correct answer (e.g., slogans), **unsupervised metrics** can assess qualities like diversity or novelty.

# This example evaluates the **semantic diversity** of slogans generated for a unique product ("Bottled Silence") using sentence embeddings.
# The `calculate_semantic_diversity_score` function computes average pairwise cosine similarity.
# A *lower* average similarity indicates *higher* semantic diversity.
# %%


def calculate_semantic_diversity_score(sentences: list[str]) -> float:
    model = sentence_transformers.SentenceTransformer("all-MiniLM-L6-v2")
    embeddings = model.encode(sentences, show_progress_bar=False)
    similarities = model.similarity(embeddings, embeddings).numpy()
    indices = np.triu_indices_from(similarities, k=1)  # k=1 excludes the diagonal
    unique_distances = similarities[indices]
    return float(np.mean(unique_distances))


@task("Slogan Semantic Diversity")
def slogans_creativity(llm) -> float:
    llm.support_structured_outputs = False
    response = llm.prompt(
        """
You are an avant-garde marketing genius tasked with branding a truly unique product: "Bottled Silence."
Your mission is to generate 10 distinct and highly imaginative slogans for "Bottled Silence."

Each slogan should:
1.  Be concise (under 15 words).
2.  Evoke a specific feeling, benefit, or mystery associated with "Bottled Silence."
3.  Be significantly different from the others in tone, style, and the aspect of "silence" it highlights.
4.  Avoid common marketing clichés. Aim for poetic, witty, or thought-provoking language.

Produce a list of 10 slogans.""",
        schema={"slogans": list[str]},
    )
    if len(response.slogans) != 10:
        return 0.0
    sentences = [
        s.lower().replace("bottled", "").replace("silence", "")
        for s in response.slogans
    ]
    return calculate_semantic_diversity_score(sentences)


slogans_creativity.evaluate(llm=llms.values())

